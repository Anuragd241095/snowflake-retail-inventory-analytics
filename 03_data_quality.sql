
-- Retail Sales & Inventory Intelligence
-- Step 3: Data Quality Validation

-- 1. Check missing values
SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(DATE IS NULL) AS MISSING_DATES,
    COUNT_IF(STORE_ID IS NULL) AS MISSING_STORES,
    COUNT_IF(PRODUCT_ID IS NULL) AS MISSING_PRODUCTS,
    COUNT_IF(INVENTORY_LEVEL IS NULL) AS MISSING_INVENTORY,
    COUNT_IF(UNITS_SOLD IS NULL) AS MISSING_SALES,
    COUNT_IF(PRICE IS NULL) AS MISSING_PRICES
FROM RETAIL_DB.RAW.RETAIL_INVENTORY;

-- 2. Check duplicate store-product-date records
SELECT
    DATE,
    STORE_ID,
    PRODUCT_ID,
    COUNT(*) AS DUPLICATE_COUNT
FROM RETAIL_DB.RAW.RETAIL_INVENTORY
GROUP BY DATE, STORE_ID, PRODUCT_ID
HAVING COUNT(*) > 1
ORDER BY DUPLICATE_COUNT DESC;

-- 3. Check invalid numerical values
SELECT
    COUNT_IF(INVENTORY_LEVEL < 0)
        AS NEGATIVE_INVENTORY,
    COUNT_IF(UNITS_SOLD < 0)
        AS NEGATIVE_SALES,
    COUNT_IF(UNITS_ORDERED < 0)
        AS NEGATIVE_ORDERS,
    COUNT_IF(PRICE <= 0)
        AS INVALID_PRICES,
    COUNT_IF(DISCOUNT < 0 OR DISCOUNT > 100)
        AS INVALID_DISCOUNTS,
    COUNT_IF(DEMAND_FORECAST < 0)
        AS NEGATIVE_FORECAST
FROM RETAIL_DB.RAW.RETAIL_INVENTORY;

-- 4. Inspect negative forecast records
SELECT
    DATE,
    STORE_ID,
    PRODUCT_ID,
    INVENTORY_LEVEL,
    UNITS_SOLD,
    DEMAND_FORECAST
FROM RETAIL_DB.RAW.RETAIL_INVENTORY
WHERE DEMAND_FORECAST < 0
ORDER BY DEMAND_FORECAST ASC
LIMIT 20;
