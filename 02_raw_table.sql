
-- Retail Sales & Inventory Intelligence
-- Step 2: Create the RAW Inventory Table

CREATE TABLE IF NOT EXISTS RETAIL_DB.RAW.RETAIL_INVENTORY (
    DATE DATE,
    STORE_ID VARCHAR(20),
    PRODUCT_ID VARCHAR(20),
    CATEGORY VARCHAR(50),
    REGION VARCHAR(50),
    INVENTORY_LEVEL NUMBER,
    UNITS_SOLD NUMBER,
    UNITS_ORDERED NUMBER,
    DEMAND_FORECAST NUMBER(12,2),
    PRICE NUMBER(12,2),
    DISCOUNT NUMBER(5,2),
    WEATHER_CONDITION VARCHAR(50),
    HOLIDAY_PROMOTION NUMBER,
    COMPETITOR_PRICING NUMBER(12,2),
    SEASONALITY VARCHAR(30)
);

-- Verify the table structure
DESCRIBE TABLE RETAIL_DB.RAW.RETAIL_INVENTORY;

-- Verify loaded record count
SELECT COUNT(*) AS TOTAL_RECORDS
FROM RETAIL_DB.RAW.RETAIL_INVENTORY;

-- Preview the first 10 rows
SELECT *
FROM RETAIL_DB.RAW.RETAIL_INVENTORY
LIMIT 10;
