-- 1. DAILY SALES ANALYTICS
-- Calculates estimated sales for each store per day.

CREATE OR REPLACE VIEW
RETAIL_DB.ANALYTICS.DAILY_SALES AS

SELECT
    DATE,
    STORE_ID,
    SUM(UNITS_SOLD) AS TOTAL_UNITS_SOLD,

    ROUND(
        SUM(UNITS_SOLD * PRICE), 2
    ) AS GROSS_SALES_VALUE,

    ROUND(
        SUM(
            UNITS_SOLD * PRICE *
            (1 - DISCOUNT / 100)
        ), 2
    ) AS ESTIMATED_NET_SALES

FROM RETAIL_DB.CLEAN.RETAIL_INVENTORY_CLEAN
GROUP BY DATE, STORE_ID;


-- 2. INVENTORY ANALYSIS
-- Calculates estimated inventory value and stock status.

CREATE OR REPLACE VIEW
RETAIL_DB.ANALYTICS.INVENTORY_ANALYSIS AS

SELECT
    DATE,
    STORE_ID,
    PRODUCT_ID,
    CATEGORY,
    REGION,
    INVENTORY_LEVEL,
    UNITS_SOLD,
    UNITS_ORDERED,
    PRICE,

    ROUND(
        INVENTORY_LEVEL * PRICE, 2
    ) AS ESTIMATED_INVENTORY_VALUE,

    CASE
        WHEN INVENTORY_LEVEL = 0
            THEN 'OUT OF STOCK'
        WHEN INVENTORY_LEVEL < 50
            THEN 'LOW STOCK'
        WHEN INVENTORY_LEVEL < 150
            THEN 'MEDIUM STOCK'
        ELSE 'SUFFICIENT STOCK'
    END AS STOCK_STATUS

FROM RETAIL_DB.CLEAN.RETAIL_INVENTORY_CLEAN;


-- 3. PRODUCT PERFORMANCE
-- Ranks products by total units sold.

CREATE OR REPLACE VIEW
RETAIL_DB.ANALYTICS.PRODUCT_PERFORMANCE AS

SELECT
    PRODUCT_ID,
    SUM(UNITS_SOLD) AS TOTAL_UNITS_SOLD,

    ROUND(
        SUM(
            UNITS_SOLD * PRICE *
            (1 - DISCOUNT / 100)
        ), 2
    ) AS ESTIMATED_NET_SALES,

    COUNT(DISTINCT STORE_ID) AS STORES_SOLD_IN,

    DENSE_RANK() OVER (
        ORDER BY SUM(UNITS_SOLD) DESC
    ) AS SALES_RANK

FROM RETAIL_DB.CLEAN.RETAIL_INVENTORY_CLEAN
GROUP BY PRODUCT_ID;


-- 4. LATEST INVENTORY SNAPSHOT
-- Keeps the latest inventory record for each store-product.

CREATE OR REPLACE VIEW
RETAIL_DB.ANALYTICS.LATEST_INVENTORY AS

SELECT
    DATE,
    STORE_ID,
    PRODUCT_ID,
    CATEGORY,
    REGION,
    INVENTORY_LEVEL,
    UNITS_SOLD,
    UNITS_ORDERED,
    PRICE,
    ESTIMATED_INVENTORY_VALUE,
    STOCK_STATUS

FROM RETAIL_DB.ANALYTICS.INVENTORY_ANALYSIS

QUALIFY ROW_NUMBER() OVER (
    PARTITION BY STORE_ID, PRODUCT_ID
    ORDER BY DATE DESC
) = 1;


-- 5. INVENTORY KPI SUMMARY
-- Calculates KPIs for the latest inventory snapshot.

CREATE OR REPLACE VIEW
RETAIL_DB.ANALYTICS.INVENTORY_KPIS AS

SELECT
    MAX(DATE) AS SNAPSHOT_DATE,
    COUNT(*) AS TOTAL_STORE_PRODUCTS,

    COUNT(DISTINCT PRODUCT_ID) AS UNIQUE_PRODUCTS,
    COUNT(DISTINCT STORE_ID) AS TOTAL_STORES,

    SUM(INVENTORY_LEVEL) AS TOTAL_STOCK_UNITS,

    ROUND(
        SUM(ESTIMATED_INVENTORY_VALUE), 2
    ) AS TOTAL_RETAIL_INVENTORY_VALUE,

    COUNT_IF(STOCK_STATUS = 'LOW STOCK')
        AS LOW_STOCK_COUNT,

    COUNT_IF(STOCK_STATUS = 'OUT OF STOCK')
        AS OUT_OF_STOCK_COUNT

FROM RETAIL_DB.ANALYTICS.LATEST_INVENTORY;
